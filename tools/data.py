def tp_tn_tab(nodes, arcs):
    tp = [0] * (nodes + 1)
    for j in range(2, nodes + 1):
        inc = [a for a in arcs if a[1] == j]
        tp[j] = max(tp[a[0]] + a[2] for a in inc) if inc else tp[j]
    T = tp[nodes]
    tn = [T] * (nodes + 1)
    for i in range(nodes - 1, 0, -1):
        out = [a for a in arcs if a[0] == i]
        tn[i] = min(tn[a[1]] - a[2] for a in out) if out else T
    return tp, tn, T


