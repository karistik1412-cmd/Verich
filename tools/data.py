def net(arcs, n):
    """arcs: (name, i, j, t)"""
    tp = {i: 0 for i in range(1, n + 1)}
    for j in range(2, n + 1):
        inc = [a for a in arcs if a[2] == j]
        tp[j] = max(tp[a[1]] + a[3] for a in inc) if inc else 0
    T = tp[n]
    tn = {i: T for i in range(1, n + 1)}
    for i in range(n - 1, 0, -1):
        out = [a for a in arcs if a[1] == i]
        tn[i] = min(tn[a[2]] - a[3] for a in out) if out else T
    return tp, tn, T


def params51():
    arcs = T51_ARCS + T51_DUMMY
    tp, tn, T = net(arcs, 9)
    rows = []
    for (name, i, j, t) in T51_ARCS:
        rows.append(dict(name=f"{name} ({i},{j})", i=i, j=j, t=t, es=tp[i], ef=tp[i] + t,
                         ls=tn[j] - t, lf=tn[j],
                         rp=tn[j] - tp[i] - t, rs=tp[j] - tp[i] - t,
                         rn=max(0, tp[j] - tn[i] - t)))
    return tp, tn, T, rows


